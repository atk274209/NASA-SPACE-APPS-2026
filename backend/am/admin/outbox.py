"""Ground-report outbox: authorized, deterministic export packages.

"Only authorized data leaves the device" is implemented as three explicit steps:
  1. A named person chooses the astronaut, the mission days and the sections, and gives a
     reason. Nothing outside that selection is written to the package.
  2. AM writes deterministic JSON and a Markdown rendering of the same data to
     data_dir/outbox/<id>/ (optionally sealed in the AMBK1 container), records a
     SyncPackage with the SHA-256 and size of the JSON file, and audits who authorized it.
  3. AM never transmits anything. A person moves the file over the mission's approved link
     and then marks the package as exported, which is audited as well.

Deterministic: the same stored records, request and package metadata always produce
byte-identical files (sorted keys, records ordered by id, fixed formatting, no clock or
randomness inside the renderers), so anyone can recompute and compare the SHA-256.
Encrypted files differ on every run (random salt and nonce); their decrypted content is
deterministic in the same way.
"""

