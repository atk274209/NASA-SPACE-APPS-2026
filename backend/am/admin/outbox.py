def _latest_mission(s: Session, astronaut_id: int) -> Mission | None:
    return s.scalars(select(Mission).where(Mission.astronaut_id == astronaut_id)
                     .order_by(Mission.id.desc()).limit(1)).first()


def validate_request(s: Session, req: ReportRequest) -> ReportRequest:
    """Check the request against stored data; returns it with sections de-duplicated in canonical order."""
    if s.get(Astronaut, req.astronaut_id) is None:
        raise LookupError("astronaut not found")
    if _latest_mission(s, req.astronaut_id) is None:
        raise ValueError("astronaut has no mission; mission days are undefined")
    today = current_mission_day(s, req.astronaut_id) or 0
    if not 1 <= req.first_day <= req.last_day <= today:
        raise ValueError(f"day range must satisfy 1 <= first_day <= last_day <= {today} (today's mission day)")
    unknown = sorted(set(req.sections) - set(SECTIONS))
    if unknown:
        raise ValueError(f"unknown sections: {unknown}; choose from {list(SECTIONS)}")
    if not req.sections:
        raise ValueError("choose at least one section")
    if not req.authorized_by.strip() or len(req.reason.strip()) < 3:
        raise ValueError("a named person and a reason are required to authorize a package")
    ordered = tuple(x for x in SECTIONS if x in set(req.sections))
    return ReportRequest(req.astronaut_id, req.first_day, req.last_day, ordered, req.authorized_by.strip(),
                         req.reason.strip())


def build_report(s: Session, req: ReportRequest, *, package_id: int, created_at: datetime,
                 thresholds: ThresholdConfig) -> dict[str, Any]:
    """Pure function of stored records + request + package metadata (no clock, no randomness)."""
    astronaut = s.get(Astronaut, req.astronaut_id)
    mission = _latest_mission(s, req.astronaut_id)
    if astronaut is None or mission is None:
        raise LookupError("astronaut or mission not found")
    start, _ = day_bounds(mission.start_date, req.first_day)
    _, end = day_bounds(mission.start_date, req.last_day)
    period = Period(req.first_day, req.last_day, start, end)
    prov = _Provenance()
    prov.add("astronaut", astronaut.id, astronaut.is_simulated)
    prov.add("mission", mission.id, mission.is_simulated)
    sections = {name: BUILDERS[name](s, astronaut.id, period, prov) for name in req.sections}
    record_ids = prov.record_ids()
    return {
        "format": REPORT_FORMAT,
        "generator": GENERATOR,
        "notice": NOTICE,
        "package": {"id": package_id, "created_at": _iso(created_at), "authorized_by": req.authorized_by,
                    "reason": req.reason},
        "astronaut": {"id": astronaut.id, "code": astronaut.code, "display_name": astronaut.display_name,
                      "is_simulated": astronaut.is_simulated},
        "mission": {"id": mission.id, "name": mission.name, "start_date": mission.start_date.isoformat(),
                    "planned_days": mission.planned_days, "environment": mission.environment,
                    "is_simulated": mission.is_simulated},
        "period": {"first_day": req.first_day, "last_day": req.last_day, "start_utc": _iso(start),
                   "end_utc": _iso(end),
                   "day_definition": "Mission day 1 is the mission start date. Days run from 00:00 to 24:00 UTC; "
                                     "end_utc is exclusive."},
        "sections_included": list(req.sections),
        "sections_not_included": [x for x in SECTIONS if x not in req.sections],
        "provenance": {
            "thresholds": {"version": thresholds.version, "label": thresholds.label},
            "simulated": prov.simulated > 0,
            "simulated_records": prov.simulated,
            "record_ids": record_ids,
            "record_counts": {k: len(v) for k, v in record_ids.items()},
        },
        "sections": sections,
    }


def render_json(report: dict[str, Any]) -> bytes:
    # allow_nan=False: a non-finite number fails loudly instead of producing invalid JSON
    return (json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n").encode("utf-8")


# ------------------------------------------------------------------ markdown
def _esc(value: Any) -> str:
    """Plain text for Markdown: no raw HTML from free-text fields reaches a renderer."""
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _cell(value: Any) -> str:
    if value is None or value == "":
        return "–"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return " ".join(_esc(value).replace("\\", "\\\\").replace("|", "\\|").split())


def _table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return out + [""]


def _quote(text: str) -> list[str]:
    return [f"> {_esc(line)}" if line.strip() else ">" for line in text.strip().splitlines()] + [""]


def _num(v: Any, digits: int = 2) -> str:
    return "–" if v is None else f"{v:.{digits}f}" if isinstance(v, float) else str(v)


def _text_of(item: Any) -> str:
    """Readable text of a stored reason/flag/observation entry, whatever its shape."""
    if isinstance(item, dict):
        for key in ("text", "reason", "label"):
            if item.get(key):
                return str(item[key])
        return json.dumps(item, sort_keys=True, ensure_ascii=False)
    return str(item)


def _md_alerts(sec: dict[str, Any]) -> list[str]:
    rows = [[a["id"], a["metric_code"].replace("_", " "), a["context"], a["severity"], a["peak_severity"],
             a["status"], a["first_seen_at"], a["resolved_at"],
             f"{_num(a['last_deviation'], 1)} / {_num(a['peak_deviation'], 1)}", a["threshold_label"],
             "yes" if a["is_simulated"] else "no"] for a in sec["records"]]
    out = _table(["Alert", "Indicator", "Context", "Severity", "Peak", "Status", "First seen (UTC)",
                  "Resolved (UTC)", "Deviation last / peak", "Thresholds", "Simulated"], rows)
    for a in sec["records"]:
        out.append(f"Alert {a['id']} explanation: {_cell(a['explanation'])}. Evidence measurement ids: "
                   f"{', '.join(str(e['measurement_id']) for e in a['evidence']) or 'none'}.")
        for r in a["reviews"]:
            out.append(f"- {r['created_at']}: {_cell(r['actor'])} ({r['action']}) {_cell(r['note'])}")
        out.append("")
    return out


def _md_journal(sec: dict[str, Any]) -> list[str]:
    out: list[str] = []
    if sec["days_without_entry"]:
        out += [f"No stored journal entry for mission days: {', '.join(map(str, sec['days_without_entry']))}.", ""]
    for e in sec["records"]:
        out += [f"### Mission day {e['mission_day']} ({e['day_date']}): level {e['day_level']}"
                f"{' (simulated)' if e['is_simulated'] else ''}", ""]
        for r in e["day_level_reasons"]:
            out.append(f"- Level reason: {_cell(_text_of(r))}")
        for f in e["flags"]:
            severity = f.get("severity") if isinstance(f, dict) else None
            out.append(f"- Flag{' (' + _cell(severity) + ')' if severity else ''}: {_cell(_text_of(f))}")
        for o in e["observations"]:
            out.append(f"- Observation: {_cell(_text_of(o))}")
        if e["day_level_reasons"] or e["flags"] or e["observations"]:
            out.append("")
        n = e["narrative"]
        if n:
            unverified = (n.get("grounding") or {}).get("unverified_numbers") or []
            out.append(f"Narrative, generated by {_cell(n['generated_by'])}"
                       f"{' (' + _cell(n['model']) + ')' if n.get('model') else ''}"
                       f"{'; numbers not found in the records: ' + ', '.join(map(str, unverified)) if unverified else ''}:")
            out += [""] + _quote(n["text"])
    return out


def _md_observations(sec: dict[str, Any]) -> list[str]:
    out: list[str] = []
    for o in sec["records"]:
        out += [f"### Observation {o['id']}: {_cell(o['title'])}", "",
                f"Status: {o['status']}. Evidence level: {o['evidence_level']}. Hypothesis generated by: "
                f"{o['generated_by']}{' (' + _cell(o['model']) + ')' if o['model'] else ''}."
                f"{' Simulated data.' if o['is_simulated'] else ''}", ""]
        out += _quote(o["observation"])
        if o["hypothesis"]:
            out += ["Hypothesis (not a conclusion):", ""] + _quote(o["hypothesis"])
        out += [f"Confidence: {_cell(o['confidence_note'])}", ""]
        for f in o["findings"]:
            out.append(f"- Finding {f['id']} ({f['finding_type']}, days {f['first_day']}-{f['last_day']}, "
                       f"n={f['n_days']}, rho={_num(f['rho'])}, p={_num(f['p_value'], 4)}, q={_num(f['q_value'], 4)}): "
                       f"{_cell(f['summary'])} {_cell(f['caveat'])}")
        out.append("")
    return out


def _md_symptoms(sec: dict[str, Any]) -> list[str]:
    rows = [[r["id"], r["label"], r["severity"], r["reported_at"], r["onset_at"], r["status"], r["resolved_at"],
             r["source"], "yes (DEMO list)" if r["report_promptly"] else "no", r["note"],
             "yes" if r["is_simulated"] else "no"] for r in sec["records"]]
    return _table(["Report", "Symptom", "Severity (self-rated)", "Reported (UTC)", "Onset (UTC)", "Status",
                   "Resolved (UTC)", "Source", "Report promptly", "Note", "Simulated"], rows) + \
        [f"Report promptly: {_esc(sec['report_promptly_label'])}", ""]


def _md_checkins(sec: dict[str, Any]) -> list[str]:
    rows = [[c["recorded_at"], ", ".join(f"{k.replace('_', ' ')} {_num(v, 0)}" for k, v in sorted(c["ratings"].items())),
             c["note"], ", ".join(map(str, c["self_report_ids"])), "yes" if c["is_simulated"] else "no"]
            for c in sec["records"]]
    return [_esc(sec["scale"]), ""] + _table(["Recorded (UTC)", "Ratings", "Note", "Record ids", "Simulated"], rows)


def _md_missions(sec: dict[str, Any]) -> list[str]:
    out = [_esc(sec["protocol_note"]), ""]
    for d in sec["records"]:
        out += [f"### Mission day {d['mission_day']}: {d['done']} of {d['total']} done", ""]
        out += _table(["Task", "Priority", "Status", "Completed by", "Protocol", "Reason"],
                      [[t["title"], t["priority"], t["status"], t["completed_by"], t["protocol_ref"], t["reason"]]
                       for t in d["tasks"]])
    return out


MD_SECTIONS: dict[str, Callable[[dict[str, Any]], list[str]]] = {
    "alerts": _md_alerts, "journal": _md_journal, "observations": _md_observations, "symptoms": _md_symptoms,
    "checkins": _md_checkins, "missions": _md_missions,
}


def render_markdown(report: dict[str, Any]) -> bytes:
    pkg, a, m, per, prov = (report["package"], report["astronaut"], report["mission"], report["period"],
                            report["provenance"])
    lines = [f"# AM ground report {pkg['id']}", ""] + _quote(report["notice"])
    lines += _table(["Field", "Value"], [
        ["Package", f"{pkg['id']}, prepared {pkg['created_at']}"],
        ["Authorized by", pkg["authorized_by"]],
        ["Reason", pkg["reason"]],
        ["Crew member", f"{a['code']} ({a['display_name']}){', simulated' if a['is_simulated'] else ''}"],
        ["Mission", f"{m['name']}, environment {m['environment']}, started {m['start_date']}"],
        ["Mission days", f"{per['first_day']} to {per['last_day']} ({per['start_utc']} to {per['end_utc']}, "
                         "end exclusive)"],
        ["Sections included", ", ".join(report["sections_included"])],
        ["Sections not included", ", ".join(report["sections_not_included"]) or "none"],
        ["Thresholds", f"{prov['thresholds']['label']} ({prov['thresholds']['version']})"],
        ["Contains simulated data", "yes" if prov["simulated"] else "no"],
    ])
    for name in report["sections_included"]:
        sec = report["sections"][name]
        lines += [f"## {SECTION_TITLES[name]}", "", _esc(sec["selection"]), ""]
        lines += MD_SECTIONS[name](sec) if sec["records"] else ["No records in this period.", ""]
    lines += ["## Provenance", "", "Record ids included in this report, by record type:", ""]
    lines += _table(["Record type", "Count", "Ids"],
                    [[k, len(v), ", ".join(map(str, v))] for k, v in prov["record_ids"].items()])
    lines += [f"Generator: {report['generator']}, format {report['format']}. The JSON file is the authoritative "
              "version of this report.", ""]
    return "\n".join(lines).encode("utf-8")


# ------------------------------------------------------------------ packages
def _fresh_folder(folder: Path) -> None:
    """Create the package folder. A leftover folder with the same id (for example after a database restore)
    is moved aside, never overwritten or deleted."""
    if folder.exists():
        folder.rename(folder.with_name(f"{folder.name}.superseded-{utcnow():%Y%m%dT%H%M%S%fZ}"))
    folder.mkdir(parents=True)


def prepare_ground_report(s: Session, settings: Settings, thresholds: ThresholdConfig, req: ReportRequest, *,
                          encrypt: bool = False, passphrase: str | None = None) -> SyncPackage:
    req = validate_request(s, req)
    if encrypt:
        if not passphrase:
            raise ValueError("a passphrase is required to encrypt the report")
        check_passphrase(passphrase)
    elif passphrase:
        raise ValueError("a passphrase was given but encrypt is false; nothing was written")
    created = utcnow()
    pkg = SyncPackage(astronaut_id=req.astronaut_id, kind=KIND, authorized_by=req.authorized_by, reason=req.reason,
                      encrypted=encrypt, status=STATUS_PREPARED, created_at=created, scope={})
    s.add(pkg)
    s.flush()  # the id names the folder and appears in the report
    report = build_report(s, req, package_id=pkg.id, created_at=created, thresholds=thresholds)
    base = f"am-ground-report-{pkg.id}"
    files = [(f"{base}.json", render_json(report)), (f"{base}.md", render_markdown(report))]
    if encrypt:
        files = [(f"{name}.ambk", encrypt_bytes(data, passphrase or "")) for name, data in files]
    folder = outbox_dir(settings) / str(pkg.id)
    _fresh_folder(folder)
    try:
        entries = []
        for name, data in files:
            atomic_write(folder / name, data)
            entries.append({"name": name, "media_type": media_type(name), "sha256": sha256_bytes(data),
                            "size_bytes": len(data)})
        primary = entries[0]
        pkg.file_path = (folder / primary["name"]).relative_to(settings.data_dir).as_posix()
        pkg.sha256, pkg.size_bytes = primary["sha256"], primary["size_bytes"]
        pkg.scope = {"format": REPORT_FORMAT, "first_day": req.first_day, "last_day": req.last_day,
                     "sections": list(req.sections), "files": entries,
                     "record_counts": report["provenance"]["record_counts"],
                     "simulated": report["provenance"]["simulated"], "thresholds_label": thresholds.label,
                     "encryption": FORMAT_DESCRIPTION if encrypt else None}
        audit(s, actor=req.authorized_by, action="outbox.prepared", entity="sync_package", entity_id=pkg.id,
              payload={"astronaut_id": req.astronaut_id, "first_day": req.first_day, "last_day": req.last_day,
                       "sections": list(req.sections), "reason": req.reason, "encrypted": encrypt,
                       "files": [{k: e[k] for k in ("name", "sha256", "size_bytes")} for e in entries]})
        s.flush()
    except Exception:
        shutil.rmtree(folder, ignore_errors=True)  # never leave a package folder the database does not list
        raise
    return pkg


def discard_files(settings: Settings, pkg: SyncPackage) -> None:
    """Remove the folder of a package whose transaction failed, so no unrecorded package remains."""
    if pkg.file_path:
        try:
            shutil.rmtree(resolve_in_data_dir(settings, pkg.file_path).parent, ignore_errors=True)
        except LookupError:
            pass


def get_package(s: Session, package_id: int) -> SyncPackage:
    pkg = s.get(SyncPackage, package_id)
    if pkg is None or pkg.kind != KIND:
        raise LookupError("ground-report package not found")
    return pkg


def mark_exported(s: Session, package_id: int, actor: str) -> SyncPackage:
    pkg = get_package(s, package_id)
    if pkg.status != STATUS_PREPARED:
        raise ValueError(f"package {package_id} is already {pkg.status}")
    pkg.status = STATUS_EXPORTED
    audit(s, actor=actor, action="outbox.exported", entity="sync_package", entity_id=pkg.id,
          payload={"sha256": pkg.sha256, "files": [f["name"] for f in (pkg.scope or {}).get("files", [])]})
    s.flush()
    return pkg


def package_file(settings: Settings, pkg: SyncPackage, name: str | None) -> tuple[Path, dict[str, Any]]:
    """Locate one file of a package and check it still matches its recorded SHA-256.

    Only names recorded in the package can be requested, so no other file is reachable.
    """
    files = (pkg.scope or {}).get("files") or []
    entry = files[0] if name is None and files else next((f for f in files if f["name"] == name), None)
    if entry is None or not pkg.file_path:
        raise LookupError("file is not part of this package")
    folder = resolve_in_data_dir(settings, pkg.file_path).parent
    path = (folder / entry["name"]).resolve()
    if path.parent != folder or not path.is_file():
        raise LookupError(f"file {entry['name']} is missing from the outbox folder")
    if sha256_file(path) != entry["sha256"]:
        raise PackageFileChanged(f"{entry['name']} has changed since it was prepared (checksum mismatch)")
    return path, entry


def record_download(s: Session, pkg: SyncPackage, entry: dict[str, Any], actor: str) -> None:
    audit(s, actor=actor, action="outbox.downloaded", entity="sync_package", entity_id=pkg.id,
          payload={"file": entry["name"], "sha256": entry["sha256"]})


def list_packages(s: Session, astronaut_id: int | None = None) -> list[SyncPackage]:
    stmt = select(SyncPackage).where(SyncPackage.kind == KIND)
    if astronaut_id is not None:
        stmt = stmt.where(SyncPackage.astronaut_id == astronaut_id)
    return list(s.scalars(stmt.order_by(SyncPackage.id.desc())).all())


def export_records(s: Session, ids: list[int]) -> dict[int, AuditLog]:
    """Latest 'outbox.exported' audit entry per package id (who marked it, and when)."""
    if not ids:
        return {}
    rows = s.scalars(select(AuditLog).where(AuditLog.action == "outbox.exported", AuditLog.entity == "sync_package",
                                            AuditLog.entity_id.in_([str(i) for i in ids]))
                     .order_by(AuditLog.id)).all()
    return {int(r.entity_id): r for r in rows if r.entity_id}


def package_summary(settings: Settings, pkg: SyncPackage, exported: AuditLog | None) -> dict[str, Any]:
    scope = pkg.scope or {}
    location = None
    if pkg.file_path:
        try:
            location = str(resolve_in_data_dir(settings, pkg.file_path).parent)
        except LookupError:
            pass
    return {
        "id": pkg.id, "kind": pkg.kind, "astronaut_id": pkg.astronaut_id, "created_at": pkg.created_at,
        "authorized_by": pkg.authorized_by, "reason": pkg.reason, "status": pkg.status, "encrypted": pkg.encrypted,
        "sha256": pkg.sha256, "size_bytes": pkg.size_bytes, "location": location,
        "first_day": scope.get("first_day"), "last_day": scope.get("last_day"),
        "sections": scope.get("sections") or [], "files": scope.get("files") or [],
        "record_counts": scope.get("record_counts") or {}, "simulated": bool(scope.get("simulated")),
        "thresholds_label": scope.get("thresholds_label"),
        "exported_by": None if exported is None else exported.actor,
        "exported_at": None if exported is None else exported.created_at,
    }
