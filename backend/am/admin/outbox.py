@dataclass(frozen=True)
class Period:
    first_day: int
    last_day: int
    start: datetime  # inclusive, naive UTC
    end: datetime  # exclusive, naive UTC

    def days(self) -> set[int]:
        return set(range(self.first_day, self.last_day + 1))


class PackageFileChanged(RuntimeError):
    """A package file on disk no longer matches the SHA-256 recorded when it was prepared."""


def outbox_dir(settings: Settings) -> Path:
    return settings.data_dir / "outbox"


def media_type(name: str) -> str:
    return MEDIA_TYPES.get(Path(name).suffix, "application/octet-stream")


def _iso(dt: datetime | None) -> str | None:
    return None if dt is None else f"{to_naive_utc(dt).isoformat()}Z"


class _Provenance:
    """Collects the id of every record written to the report, per record type."""

    def __init__(self) -> None:
        self.ids: dict[str, set[int]] = defaultdict(set)
        self.simulated = 0

    def add(self, kind: str, ident: int, simulated: bool = False) -> None:
        if ident not in self.ids[kind]:
            self.ids[kind].add(ident)
            self.simulated += bool(simulated)

    def record_ids(self) -> dict[str, list[int]]:
        return {k: sorted(v) for k, v in sorted(self.ids.items())}


