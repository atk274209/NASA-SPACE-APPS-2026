def _alerts(s: Session, astronaut_id: int, p: Period, prov: _Provenance) -> dict[str, Any]:
    rows = s.scalars(
        select(Alert)
        .where(Alert.astronaut_id == astronaut_id, Alert.first_seen_at < p.end,
               or_(Alert.resolved_at.is_(None), Alert.resolved_at >= p.start))
        .options(selectinload(Alert.evidence).selectinload(AlertEvidence.measurement), selectinload(Alert.acks))
        .order_by(Alert.id)
    ).all()
    records = []
    for a in rows:
        prov.add("alert", a.id, a.is_simulated)
        evidence = []
        for e in sorted(a.evidence, key=lambda x: x.measurement_id):
            m = e.measurement
            prov.add("measurement", m.id, m.is_simulated)
            evidence.append({"measurement_id": m.id, "recorded_at": _iso(m.recorded_at), "value": m.value,
                             "unit": m.unit, "context": m.context, "quality": m.quality, "deviation": e.deviation,
                             "severity_at_time": e.severity_at_time, "is_simulated": m.is_simulated})
        records.append({
            "id": a.id, "metric_code": a.metric_code, "context": a.context, "direction": a.direction,
            "severity": a.severity, "peak_severity": a.peak_severity, "status": a.status, "rule_id": a.rule_id,
            "threshold_version": a.threshold_version, "threshold_label": a.threshold_label,
            "baseline_profile_id": a.baseline_profile_id, "last_deviation": a.last_deviation,
            "peak_deviation": a.peak_deviation, "persistence_count": a.persistence_count,
            "explanation": a.explanation, "first_seen_at": _iso(a.first_seen_at), "last_seen_at": _iso(a.last_seen_at),
            "resolved_at": _iso(a.resolved_at), "is_simulated": a.is_simulated, "evidence": evidence,
            "reviews": [{"action": k.action, "actor": k.actor, "note": k.note, "created_at": _iso(k.created_at)}
                        for k in sorted(a.acks, key=lambda x: x.id)],
        })
    return {"selection": "Alerts open at any time during the period, with their supporting measurements and review "
                         "history. Deviations are robust z-scores against the personal baseline. Status is as of "
                         "report creation.",
            "records": records}


def _journal(s: Session, astronaut_id: int, p: Period, prov: _Provenance) -> dict[str, Any]:
    rows = s.scalars(select(JournalEntry).where(
        JournalEntry.astronaut_id == astronaut_id, JournalEntry.mission_day >= p.first_day,
        JournalEntry.mission_day <= p.last_day).order_by(JournalEntry.mission_day)).all()
    records = []
    for e in rows:
        prov.add("journal_entry", e.id, e.is_simulated)
        narrative = None
        if e.narrative:
            narrative = {"text": e.narrative, "generated_by": e.narrative_generated_by, "model": e.narrative_model,
                         "grounding": e.narrative_grounding or {}, "generated_at": _iso(e.narrative_generated_at)}
        records.append({
            "id": e.id, "mission_day": e.mission_day, "day_date": e.day_date.isoformat(), "day_level": e.day_level,
            "day_level_reasons": e.day_level_reasons or [], "summary": e.sections or {}, "flags": e.flags or [],
            "observations": e.observations or [], "refs": e.refs or [], "complete_day": e.complete_day,
            "is_simulated": e.is_simulated, "generator_version": e.generator_version,
            "generated_at": _iso(e.generated_at), "narrative": narrative,
        })
    present = {e.mission_day for e in rows}
    return {"selection": "Stored journal entries for the mission days in the period. Missing days are listed; AM "
                         "does not generate entries for the report.",
            "records": records,
            "days_without_entry": [d for d in range(p.first_day, p.last_day + 1) if d not in present]}


def _observations(s: Session, astronaut_id: int, p: Period, prov: _Provenance) -> dict[str, Any]:
    rows = s.scalars(select(ResearchObservation).where(ResearchObservation.astronaut_id == astronaut_id)
                     .order_by(ResearchObservation.id)).all()
    wanted = sorted({fid for o in rows for fid in (o.finding_ids or [])})
    findings = ({f.id: f for f in s.scalars(select(ResearchFinding).where(ResearchFinding.id.in_(wanted)))}
                if wanted else {})
    days = p.days()
    records = []
    for o in rows:
        linked = [findings[fid] for fid in (o.finding_ids or []) if fid in findings]
        if not (any(days & set(f.days or []) for f in linked) or p.start <= o.created_at < p.end):
            continue
        prov.add("research_observation", o.id, o.is_simulated)
        for f in linked:
            prov.add("research_finding", f.id)
        records.append({
            "id": o.id, "title": o.title, "status": o.status, "evidence_level": o.evidence_level,
            "observation": o.observation, "scientific_context": o.scientific_context, "hypothesis": o.hypothesis,
            "generated_by": o.generated_by, "model": o.model, "confidence_note": o.confidence_note,
            "grounding": o.grounding or {}, "doc_refs": o.doc_refs or [], "is_simulated": o.is_simulated,
            "created_at": _iso(o.created_at), "finding_ids": list(o.finding_ids or []),
            "findings": [{"id": f.id, "finding_type": f.finding_type, "summary": f.summary, "caveat": f.caveat,
                          "n_days": f.n_days, "lag_days": f.lag_days, "rho": f.rho, "p_value": f.p_value,
                          "q_value": f.q_value, "first_day": min(f.days) if f.days else None,
                          "last_day": max(f.days) if f.days else None} for f in linked],
        })
    return {"selection": "Research observations whose statistical findings cover days in the period, or that were "
                         "recorded during it. Findings are screening statistics and do not establish causation. "
                         "Status 'draft' means no person has reviewed the observation yet.",
            "records": records}


