import type { ReactNode } from 'react'
import { ApiError } from '../api/client'
import { severityColor } from '../lib/format'

export function SeverityTag({ severity, size = 'sm' }: { severity: string | null | undefined; size?: 'sm' | 'lg' }) {
  const label = severity ? severity.charAt(0) + severity.slice(1).toLowerCase() : 'Unassessed'
  const color = severityColor(severity)
  return (
    <span
      className={`inline-flex items-center gap-1.5 font-medium ${size === 'lg' ? 'text-lg' : 'text-sm'}`}
      style={{ color }}
    >
      <span
        aria-hidden
        className={size === 'lg' ? 'size-2.5 rounded-full' : 'size-2 rounded-full'}
        style={{ background: color }}
      />
      {label}
    </span>
  )
}

export function SimulatedMark({ title = 'Generated by the AMC simulator. Not a real measurement.' }: { title?: string }) {
  return (
    <span
      title={title}
      className="sim-hatch inline-flex items-center rounded-sm border border-[color:var(--color-sim)]/50 px-1.5 py-px text-xs font-medium text-sim"
    >
      Simulated
    </span>
  )
}

export function DemoThresholdNote({ label }: { label: string }) {
  return (
    <span className="text-xs text-sev-watch" title="Alert bands are demonstration values pending medical review.">
      {label}
    </span>
  )
}

/** Section with a heading rule. Hierarchy comes from spacing and type, not from boxes. */
export function Section({
  title,
  aside,
  children,
  className = '',
}: {
  title: ReactNode
  aside?: ReactNode
  children: ReactNode
  className?: string
}) {
  return (
    <section className={`min-w-0 ${className}`}>
      <header className="mb-3 flex items-baseline justify-between gap-4 border-b border-seam pb-2">
        <h2 className="text-base font-semibold text-ink">{title}</h2>
        {aside && <div className="text-sm text-ink-dim">{aside}</div>}
      </header>
      {children}
    </section>
  )
}

export function Empty({ title, children }: { title: string; children?: ReactNode }) {
  return (
    <div className="rounded-md border border-dashed border-seam-strong px-5 py-8 text-center">
      <p className="font-medium text-ink">{title}</p>
      {children && <div className="mt-1 text-sm text-ink-dim">{children}</div>}
    </div>
  )
}

export function ErrorNote({ error }: { error: unknown }) {
  const msg =
    error instanceof ApiError ? error.message : error instanceof Error ? error.message : 'Unexpected error.'
  return (
    <div role="alert" className="rounded-md border border-sev-critical/40 bg-sev-critical/10 px-4 py-3 text-sm text-ink">
      {msg}
    </div>
  )
}

export function Loading({ label = 'Loading' }: { label?: string }) {
  return <p className="py-6 text-sm text-ink-faint">{label}…</p>
}

export function Field({ label, children }: { label: string; children: ReactNode }) {
  return (
    <label className="flex flex-col gap-1 text-sm">
      <span className="text-ink-dim">{label}</span>
      {children}
    </label>
  )
}

export const inputCls =
  'rounded-md border border-seam-strong bg-deck px-2.5 py-1.5 text-ink placeholder:text-ink-faint focus:border-signal focus:outline-none'

export function Button({
  children,
  variant = 'primary',
  ...rest
}: React.ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'quiet' }) {
  const cls =
    variant === 'primary'
      ? 'bg-ink text-void hover:bg-white disabled:bg-seam-strong disabled:text-ink-faint'
      : 'border border-seam-strong text-ink hover:border-signal disabled:text-ink-faint'
  return (
    <button
      {...rest}
      className={`inline-flex items-center justify-center rounded-md px-3 py-1.5 text-sm font-medium transition-colors disabled:cursor-not-allowed ${cls} ${rest.className ?? ''}`}
    >
      {children}
    </button>
  )
}

export function KeyValue({ items }: { items: [ReactNode, ReactNode][] }) {
  return (
    <dl className="grid grid-cols-[auto_1fr] gap-x-6 gap-y-1.5 text-sm">
      {items.map(([k, v], i) => (
        <div key={i} className="contents">
          <dt className="text-ink-dim">{k}</dt>
          <dd className="min-w-0 text-ink">{v}</dd>
        </div>
      ))}
    </dl>
  )
}

/** The AMC mark: a ring (the station) around a core (the mind at its centre). */
